#!/usr/bin/env bash
# =============================================================================
# download-exe.sh — скачать исполняемые winPEAS из официального релиза PEASS-ng
# =============================================================================
# ЗАЧЕМ: сами .exe НЕ хранятся в этом репозитории. GitHub push-protection
#   блокирует их, потому что внутри winPEAS зашиты сигнатуры для поиска чужих
#   секретов, а secret-scanning принимает их за настоящие ключи (ложное
#   срабатывание). Поэтому бинарники тянем по требованию из релиза проекта.
#
# ЗАПУСК:  bash download-exe.sh
# =============================================================================
set -e
BASE="https://github.com/peass-ng/PEASS-ng/releases/latest/download"
cd "$(dirname "$0")"
for f in winPEASx64.exe winPEASany.exe winPEASx86.exe; do
    echo "[*] Скачиваю $f ..."
    curl -L --fail "$BASE/$f" -o "$f" && echo "[+] $f" || echo "[-] не удалось: $f"
done
echo "[+] Готово. Для 64-бит цели используйте winPEASx64.exe"
